# S1-J-3 golden-fixture harness — verbatim source extractor.
#
# Regenerates Generated/*.cs from the decompiled Terraria 1.4.5.8 tree so the
# harness runs the REAL save-path method bodies (the S1-J-1 / S1-A-1 oracle
# pattern: the decompile is the source, only the global lookups become shim
# statics). Run from the repo root:
#
#   powershell -File tools/WldFixtureHarness/extract.ps1
#
# One — and only one — textual substitution is made to the extracted bodies,
# documented in README.md:
#   * `DateTime.UtcNow`  -> `FixtureClock.UtcNow`   (a pinned clock; the vanilla
#     writer stamps the wall clock, which a reproducible fixture cannot carry)
# Everything else is byte-for-byte the decompiled method body.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)   # repo root
$dec  = Join-Path $root 'decompiled'
$out  = Join-Path $PSScriptRoot 'Generated'
New-Item -ItemType Directory -Force $out | Out-Null

function Read-Src([string]$rel) { Get-Content (Join-Path $dec $rel) -Raw }

# Extract one method body by its signature substring, brace-counting from the
# first '{' after the signature to its matching '}'. Returns the verbatim text
# (signature line through closing brace), indented as in the source.
function Extract-Method([string]$src, [string]$sig) {
    $i = $src.IndexOf($sig)
    if ($i -lt 0) { throw "signature not found: $sig" }
    # back up to the start of the signature's line
    $ls = $src.LastIndexOf("`n", $i); if ($ls -lt 0) { $ls = 0 } else { $ls += 1 }
    $b = $src.IndexOf('{', $i)
    if ($b -lt 0) { throw "no body for: $sig" }
    $depth = 0; $j = $b
    for (; $j -lt $src.Length; $j++) {
        $c = $src[$j]
        if ($c -eq '{') { $depth++ }
        elseif ($c -eq '}') { $depth--; if ($depth -eq 0) { break } }
    }
    if ($depth -ne 0) { throw "unbalanced braces for: $sig" }
    return $src.Substring($ls, $j - $ls + 1)
}

function Substitute([string]$text) {
    return $text.Replace('DateTime.UtcNow', 'FixtureClock.UtcNow')
}

