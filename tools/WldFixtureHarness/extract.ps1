# wrong same-named method: slice the class region first.
foreach ($pair in $cpKinds) {
    $name=$pair[0]; $sig=$pair[1]
    $ci = $cp.IndexOf("public class $name ")
    if ($ci -lt 0) { $ci = $cp.IndexOf("public class ${name}:") }
    if ($ci -lt 0) { throw "class not found: $name" }
    $region = $cp.Substring($ci)
    [void]$sb.AppendLine("public partial class $name`n{")
    [void]$sb.AppendLine((Extract-Method $region $sig))
    [void]$sb.AppendLine("}`n")
}
[void]$sb.AppendLine("}")
