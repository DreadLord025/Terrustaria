# W4-d37 LAGGARD-EXEC: emit the FINAL v2 per-lane master tables (markdown)
# from _d37_lag_final2.json + _d37_lag_sites2.json. Doc-generation only.
import json

REPO = r"C:\Users\DreadLord\Desktop\TR-W4-d37"
f2 = json.load(open(REPO + r"\tools\_d37_lag_final2.json"))
sites = json.load(open(REPO + r"\tools\_d37_lag_sites2.json"))
plan = f2["plan"]

lines = []
A = lines.append
A("<!-- GENERATED by tools/_d37_lag_emit2.py from _d37_lag_final2.json +")
A("     _d37_lag_sites2.json (LIVE tips, see each lane header). -->")
A("")
for lane in sorted(set(f2["moves"]) | set(f2["drops"])):
    mv = f2["moves"].get(lane, [])
    dp = f2["drops"].get(lane, [])
    A(f"### {lane} — {len(mv)} moves / {len(dp)} drops (tip `{f2['tips'][lane]}`)")
    A("")
    if mv:
        A("| Kind | old proto | new proto | to_u16 line | from_u16 line |")
        A("|---|---|---|---|---|")
        for m in sorted(mv, key=lambda x: x["old"]):
            s = sites.get(lane, {}).get(m["kind"], {"to": [], "from": []})
            A(f"| {m['kind']} | {m['old']} | **{m['new']}** | "
              f"{','.join(map(str, s['to'])) or '—'} | {','.join(map(str, s['from'])) or '—'} |")
        A("")
    if dp:
        A("| Kind | drop id | keeper lane | keeper final id | to_u16 line | from_u16 line |")
        A("|---|---|---|---|---|---|")
        for x in sorted(dp, key=lambda y: y["id"]):
            s = sites.get(lane, {}).get(x["kind"], {"to": [], "from": []})
            kid = plan.get(x["kind"], ["—"])[0]
            A(f"| {x['kind']} | {x['id']} | {x['keeper']} | {kid} | "
              f"{','.join(map(str, s['to'])) or '—'} | {','.join(map(str, s['from'])) or '—'} |")
        A("")

open(REPO + r"\tools\_d37_lag_tables2.md", "w", encoding="utf8", newline="\n").write(
    "\n".join(lines) + "\n")
print("emitted", len(lines), "lines -> tools/_d37_lag_tables2.md")
