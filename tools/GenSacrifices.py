"""GenSacrifices: the TSV -> the static sacrifices table (the gen-script
convention — like GenItemData; a second run must produce an empty diff)."""
import io
import os

os.chdir('C:/Users/DreadLord/Desktop/Terraria-Rust')

GRADES = {
    '': 50, 'a': 50, 'b': 25, 'c': 5, 'd': 1, 'f': 2, 'g': 3, 'h': 10,
    'i': 15, 'j': 30, 'k': 99, 'l': 100, 'm': 200, 'n': 20, 'o': 400,
}

src = 'decompiled/Terraria.GameContent.Creative.Content.Sacrifices.tsv'
rows = []
for line in io.open(src, encoding='utf-8'):
    line = line.rstrip('\r\n')
    if line.startswith('//'):
        continue
    parts = line.split('\t')
    if len(parts) < 2:
        continue
    name = parts[0].strip()
    grade = parts[1].strip().lower()
    if not name:
        continue
    count = GRADES.get(grade)
    if count is None:
        print('SKIP (unknown grade):', name, repr(grade))
        continue
    rows.append((name, count))

rows.sort()
out = io.open('crates/tr-app/src/creative_sacrifices.rs', 'w', encoding='utf-8', newline='')
out.write('''// @generated by tools/GenSacrifices.py from the decompiled Terraria
// sources (Terraria.GameContent.Creative.Content.Sacrifices.tsv). Do not
// edit by hand — regenerate with `python tools/GenSacrifices.py`; a second
// run must produce an empty diff.

//! `CreativeItemSacrificesCatalog`'s table (`CreativeItemSacrificesCatalog
//! .cs:17-104`): the item name (the `ItemID` const name) -> the sacrifice
//! count needed for the full research. The E-grade (the unobtainable) rows
//! are skipped like the vanilla's `flag`.

/// The (ItemID const name, needed count) rows, sorted by the name — the
/// lookup rides [`crate::itemdata::NAMES`]'s binary search.
pub static SACRIFICES: [(&str, u32); %d] = [
''' % len(rows))
for name, count in rows:
    out.write('    ("%s", %d),\n' % (name, count))
out.write('];\n')
out.close()
print('generated', len(rows), 'rows')
