# W4-d37 LAGGARD-EXEC: emit the FINAL per-lane master tables (markdown)
# from _d37_lag_master.json + the arm-line censuses. Doc-generation only.
import json

REPO = r"C:\Users\DreadLord\Desktop\TR-W4-d37"
master = json.load(open(REPO + r"\tools\_d37_lag_master.json"))
arms = json.load(open(REPO + r"\tools\_d37_lag_arms.json"))
g8new = json.load(open(REPO + r"\tools\_d37_lag_g8_newtip.json"))
seal_receipts = json.load(open(REPO + r"\tools\_d37_seal_receipts.json"))
seal = json.load(open(REPO + r"\tools\_d37_seal_final.json"))

# new-id map for drop keepers (post-move ids)
final = dict(seal["final"])
union = json.load(open(REPO + r"\tools\_d37_lag_union.json"))

TIP = {
 "c3": "c0bc6c0de", "c4": "0df6964be", "c6": "5de680219", "c7": "c2cc6ec61",
 "c8": "7c2de9c06", "c9": "2042d77f1", "c10": "5fcc68ae6", "d23": "43091b01c",
 "d35": "1afd327b9", "d120": "2408233da", "d125": "7a0482302", "d42": "bac408be0",
 "e26": "048cca6cf", "g8": "1752c70df", "d36": "1c6b5699e", "d41": "727578f2d",
 "d43": "0253bde90", "f18": "a832d38ea", "f42": "425d4ff9d", "d9": "7a418c636",
 "d11": "121672908", "f47": "18fe75f2e", "g5": "96f074959", "d40": "8fe1d6d31",
}

lines = []
A = lines.append
A("<!-- GENERATED by tools/_d37_lag_emit.py from _d37_lag_master.json +")
A("     _d37_lag_arms.json + _d37_lag_g8_newtip.json. Do not hand-edit. -->")
A("")
for lane in sorted(set(master["moves"]) | set(master["drops"])):
    mv = master["moves"].get(lane, [])
    dp = master["drops"].get(lane, [])
    A(f"### {lane} — {len(mv)} moves / {len(dp)} drops (tip `{TIP.get(lane,'?')}`)")
    A("")
    if mv:
        A("| Kind | old proto | new proto | to_u16 line | from_u16 line |")
        A("|---|---|---|---|---|")
        for m in sorted(mv, key=lambda x: x["old"]):
            k = m["kind"]
            if lane == "g8" and k in g8new:
                t = g8new[k]["to"]; f = g8new[k]["from"]
            elif lane in arms and k in arms[lane]:
                t = arms[lane][k]["to_line"]; f = arms[lane][k]["from_line"]
            else:
                t = f = []
            A(f"| {k} | {m['old']} | **{m['new']}** | {','.join(map(str,t)) or '—'} "
              f"| {','.join(map(str,f)) or '—'} |")
        A("")
    if dp:
        A("| Kind | drop id | keeper lane | keeper final id | to_u16 line | from_u16 line |")
        A("|---|---|---|---|---|---|")
        for d in sorted(dp, key=lambda x: x["id"]):
            k = d["kind"]
            keeper = d["keeper"]
            kid = union["grand"].get(k, "—")
            if lane == "g8" and k in g8new:
                t = g8new[k]["to"]; f = g8new[k]["from"]
            elif lane in arms and k in arms[lane]:
                t = arms[lane][k]["to_line"]; f = arms[lane][k]["from_line"]
            else:
                t = f = []
            A(f"| {k} | {d['id']} | {keeper} | {kid} | {','.join(map(str,t)) or '—'} "
              f"| {','.join(map(str,f)) or '—'} |")
        A("")

open(REPO + r"\tools\_d37_lag_tables.md", "w", encoding="utf8", newline="\n").write(
    "\n".join(lines) + "\n")
print("emitted", len(lines), "lines ->", r"tools\_d37_lag_tables.md")
