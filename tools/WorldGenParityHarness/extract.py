# S1-A-7 worldgen-parity harness — verbatim source extractor.
#
# Regenerates Generated/*.cs from the decompiled Terraria 1.4.5.8 tree so the
# harness runs the REAL genRand-driven worldgen leaf bodies (the S1-J-1 /
# S1-J-3 oracle pattern: the decompile is the source, only the global lookups
# become shim statics). Run from the repo root:
#
#   python tools/WorldGenParityHarness/extract.py
#
# The worldgen leaf bodies (TileRunner / PlaceWall / CanBeClearedDuringGeneration)
# are extracted with ZERO substitutions — byte-for-byte the decompiled source.
# The ONE rename is on the RNG type only: the verbatim `UnifiedRandom` class is
# emitted as `UnifiedRandomCore` so the harness's `UnifiedRandom` shim can wrap
# it (real Knuth stream) or replay the port's xorshift stream (differential
# mode). The algorithm body is untouched.
#
# SquareWallFrame (called by PlaceWall) is NOT extracted: it is a visual
# wall-framing pass the port defers (tile_runner.rs place_wall doc), and wall
# frames are runtime-only (never serialized). The harness shims it as a no-op,
# exactly the port's convention, so the comparison stays on saved fields.

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DEC = ROOT / "decompiled"
LIBS = ROOT / "decompiled-libs"
OUT = pathlib.Path(__file__).resolve().parent / "Generated"
OUT.mkdir(exist_ok=True)

BANNER = (
    "// <auto-generated> Verbatim decompiled bodies extracted by extract.py (S1-A-7).\n"
    "// Do not edit by hand; regenerate with tools/WorldGenParityHarness/extract.py.\n"
    "// No substitutions: every body is byte-for-byte the decompiled source.\n"
    "// </auto-generated>\n"
)


def read_src(path: pathlib.Path) -> str:
    return path.read_text(encoding="utf-8-sig")


def extract_method(src: str, sig: str) -> str:
    """One method body by signature substring, brace-counting from the first
    '{' after the signature to its matching '}'. Verbatim, signature line
    through closing brace, indented as in the source."""
    i = src.find(sig)
    if i < 0:
        raise SystemExit(f"signature not found: {sig}")
    ls = src.rfind("\n", 0, i) + 1
    b = src.find("{", i)
    if b < 0:
        raise SystemExit(f"no body for: {sig}")
    depth = 0
    j = b
    while j < len(src):
        c = src[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    if depth != 0:
        raise SystemExit(f"unbalanced braces for: {sig}")
    return src[ls : j + 1]


# ---- WorldGen: the genRand-driven leaf routines ------------------------------
wg = read_src(DEC / "Terraria/WorldGen.cs")
parts = [
    BANNER,
    "using System;\nusing Microsoft.Xna.Framework;\nusing ReLogic.Utilities;\n"
    "using Terraria.Audio;\nusing Terraria.ID;\nusing Terraria.Utilities;\nusing Terraria.WorldBuilding;\n"
    "using Terraria.GameContent.Generation.Dungeon;\n\n",
    "namespace Terraria;\n\npublic partial class WorldGen\n{\n",
]
for sig in [
    "public static void TileRunner(int i, int j, double strength, int steps, int type,",
    "public static void PlaceWall(int i, int j, int type, bool mute = false)",
    "public static bool CanBeClearedDuringGeneration(int tileType, int x, int y, bool skipDualDungeonCheck = false)",
]:
    parts.append(extract_method(wg, sig))
    parts.append("\n\n")
parts.append("}\n")
(OUT / "WorldGenRunner.cs").write_text("".join(parts), encoding="utf-8")

# ---- UnifiedRandom: the real genRand type (verbatim algorithm, renamed) ------
# The class is renamed UnifiedRandom -> UnifiedRandomCore so the harness shim
# `UnifiedRandom` can wrap it (real Knuth stream) or replay the port's xorshift
# stream (differential mode). The algorithm body is byte-for-byte untouched.
ur = read_src(DEC / "Terraria/Utilities/UnifiedRandom.cs")
ur = ur.replace("public class UnifiedRandom", "public class UnifiedRandomCore")
ur = ur.replace("public UnifiedRandom()", "public UnifiedRandomCore()")
ur = ur.replace("public UnifiedRandom(int Seed)", "public UnifiedRandomCore(int Seed)")
(OUT / "UnifiedRandomCore.cs").write_text(BANNER + ur, encoding="utf-8")

# ---- Vector2D: the walker's position/velocity type (verbatim whole file) -----
v2 = read_src(LIBS / "ReLogic/ReLogic.Utilities/Vector2D.cs")
(OUT / "Vector2D.cs").write_text(BANNER + v2, encoding="utf-8")

print(f"Generated files written to {OUT}")
for p in sorted(OUT.iterdir()):
    print(f"  {p.name}  ({p.stat().st_size} bytes)")
