/// `ProjectileID.Count` (`ProjectileID.cs:2832`): 1136.
pub const PROJECTILE_COUNT: i32 = 1136;

/// The constant spelling for `id`, or `"None"` for the out-of-range ids
/// (`Lang.projectile`'s array bounds cover 0..Count).
pub fn projectile_const_name(id: i32) -> &'static str {
    if id < 0 || id >= PROJECTILE_COUNT {
        return "None";
    }
    PROJECTILE_ID
        .iter()
        .find(|&&(i, _)| i == id)
        .map_or("None", |&(_, n)| n)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// S1-F-5 — the id walk: the ids 0..=1135 all present, no gaps, `Count`
    /// = 1136, the 60 alias pair carried, and the C#'s sampled spellings
    /// ride the walk (the previously-cited 3 shuriken, the 615 Vortex Beater
    /// shot, the 714 Celeb2 shot).
    #[test]
    fn the_projectile_id_walk_covers_the_csharp_table() {
        assert_eq!(PROJECTILE_COUNT, 1136, "`ProjectileID.Count = 1136`");
        let ids: Vec<i32> = PROJECTILE_ID.iter().map(|&(i, _)| i).collect();
        for id in 0..PROJECTILE_COUNT {
            assert!(ids.contains(&id), "id {id} missing from the walk");
        }
        // The 60 alias pair (`ProjectileID.cs`: both spellings carry it).
        let at_60: Vec<&str> = PROJECTILE_ID
            .iter()
            .filter(|&&(i, _)| i == 60)
            .map(|&(_, n)| n)
            .collect();
        assert_eq!(at_60, vec!["FixedDamageForRockets", "MythrilDrill"]);
        // The sampled spellings (`Shuriken = 3`, `None = 0`,
        // `ProjectileID.cs:560`/`:554`).
        assert_eq!(projectile_const_name(3), "Shuriken");
        assert_eq!(projectile_const_name(0), "None");
        for id in 0..PROJECTILE_COUNT {
            assert_ne!(
                projectile_const_name(id),
                "",
                "the walk answers every id"
            );
        }
        assert_eq!(projectile_const_name(1135).is_empty(), false);
        assert_eq!(projectile_const_name(1136), "None");
        assert_eq!(projectile_const_name(-1), "None");
    }
}
