/// `PlayerItemSlotID`'s `AllocateSlots` sequence verbatim
/// (`PlayerItemSlotID.cs:175-192`): `(const name, slot count, canNetRelay)`
/// in the C#'s walk order — the ids derive by the same accumulation
/// (`AllocateSlots` returns `_nextSlotId` before the increment), so
/// `Inventory0 = 0`, `InventoryMouseItem = 58`, `Armor0 = 59`, ...
pub const PLAYER_ITEM_SLOT_WALK: &[(&str, i32, bool)] = &[
    ("Inventory0", 58, true),
    ("InventoryMouseItem", 1, true),
    ("Armor0", 20, true),
    ("Dye0", 10, true),
    ("Misc0", 5, true),
    ("MiscDye0", 5, true),
    ("Bank1_0", 200, false),
    ("Bank2_0", 200, false),
    ("TrashItem", 1, false),
    ("Bank3_0", 200, false),
    ("Bank4_0", 200, true),
    ("Loadout1_Armor_0", 20, true),
    ("Loadout1_Dye_0", 10, true),
    ("Loadout2_Armor_0", 20, true),
    ("Loadout2_Dye_0", 10, true),
    ("Loadout3_Armor_0", 20, true),
    ("Loadout3_Dye_0", 10, true),
];

/// The accumulated `PlayerItemSlotID` values — the walk's `_nextSlotId`
/// ledger, `(const name, first slot id)`.
pub fn player_item_slot_ids() -> Vec<(&'static str, i32)> {
    let mut out = Vec::new();
    let mut next = 0;
    for &(name, count, _relay) in PLAYER_ITEM_SLOT_WALK {
        out.push((name, next as i32));
        next += count;
    }
    out
}

/// `PlayerItemSlotID.Count` (`PlayerItemSlotID.cs:192`): the ledger's total.
pub fn player_item_slot_count() -> i32 {
    PLAYER_ITEM_SLOT_WALK.iter().map(|&(_, c, _)| c).sum()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// S1-F-6 — the walks' coverage: dust carries the C#'s 196 named
    /// constants (the file's own gaps — 7, the 19..22 band, 24..28 — stay
    /// unnamed; `DustID.Count = 332` bounds the array); 343 sound styles;
    /// the sixteen armor tables' 1020 constants with their `Count` bounds;
    /// the slot ledger reproducing `Inventory0 = 58`
    /// (`PlayerItemSlotID.cs:175`).
    #[test]
    fn s1_f_6_the_id_walks_match_the_csharp_tables() {
        assert_eq!(DUST_ID.len(), 207, "every named dust constant (the t_* aliases ride)");
        assert_eq!(DUST_COUNT, 332);
        // The C#'s own gaps stay gaps (7 and the 19..22 band are unnamed).
        let dust_ids: Vec<i32> = DUST_ID.iter().map(|&(i, _)| i).collect();
        assert!(!dust_ids.contains(&7), "id 7 is unnamed in the C#");
        assert!(!dust_ids.contains(&19), "id 19 is unnamed in the C#");
        assert!(DUST_ID.iter().any(|&(_, n)| n == "t_Slime"), "the alias spelling rides");
        assert_eq!(
            DUST_ID.iter().filter(|&(_, n)| *n == "TintableDust").count(),
            1,
            "the primary spelling stays"
        );
        assert_eq!(SOUND_STYLE.len(), 343, "the sound style walk");
        assert_eq!(ARMOR_HEAD.len(), 293);
        assert_eq!(ARMOR_HEAD_COUNT, 293);
        assert_eq!(ARMOR_BODY_COUNT, 262);
        assert_eq!(ARMOR_LEGS_COUNT, 254);
        assert_eq!(ARMOR_HANDON_COUNT, 33);
        assert_eq!(ARMOR_HANDOFF_COUNT, 19);
        assert_eq!(ARMOR_BACK_COUNT, 42);
        assert_eq!(ARMOR_FRONT_COUNT, 18);
        let slots = player_item_slot_ids();
        // `AllocateSlots` returns `_nextSlotId` BEFORE the increment
        // (`PlayerItemSlotID.cs:195-206`), so `Inventory0 = 0` and the rest
        // accumulate.
        assert_eq!(slots[0], ("Inventory0", 0), "`Inventory0 = AllocateSlots(58, ...)`'s returned base");
        assert_eq!(slots[1], ("InventoryMouseItem", 58));
        assert_eq!(slots[2], ("Armor0", 59), "Armor0 follows the mouse slot");
        assert_eq!(slots[8], ("TrashItem", 499));
        assert_eq!(player_item_slot_count(), 990, "the ledger's total");
    }
}
