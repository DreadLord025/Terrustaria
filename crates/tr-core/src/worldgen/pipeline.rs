type StepFn = fn(&mut World, &mut GenVars, &mut Streams, &GenOptions, &Noise, &ConfigSection);

/// One executed step: the port's display name, the vanilla pass it executes
/// ("" when the step is not a vanilla pass — the span planner, the slope
/// pass and the world tail), and the adapter. The adapter bodies are the
/// `generate()` call sites copied verbatim.
pub(crate) struct Step {
    pub(crate) name: &'static str,
    pub(crate) vanilla: &'static str,
    pub(crate) f: StepFn,
}

macro_rules! step {
    ($name:literal, $vanilla:literal, $f:ident) => {
        Step {
            name: $name,
            vanilla: $vanilla,
            f: $f,
        }
    };
}

