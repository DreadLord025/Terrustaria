/// FNV-1a 64-bit over a pass name — the mixer that keys each per-pass stream
/// off the world seed. The offset basis and prime are the standard constants
/// (the same numbers the embedded-config provenance pin in `config.rs`'s
/// `the_embedded_copy_is_unmodified` hashes with).
#[allow(dead_code)] // the per-pass stream contract — consumed from Phase 3 on
pub(crate) fn fnv1a64(name: &str) -> u64 {
    const OFFSET_BASIS: u64 = 0xcbf2_9ce4_8422_2325;
    const PRIME: u64 = 0x0000_0100_0000_01B3;
    let mut hash = OFFSET_BASIS;
    for byte in name.bytes() {
        hash ^= byte as u64;
        hash = hash.wrapping_mul(PRIME);
    }
    hash
}

/// The three worldgen xorshift streams. The seeds are contract constants
/// (`noise.rs`: "the output streams of both are part of the world contract");
/// `Rng` construction draws nothing, so creating all three up front (vanilla
/// creates its per-pass stream inside `RunPass`) shifts no draw.
pub(crate) struct Streams<'a> {
    /// The world seed everything here derives from (`new`'s argument, kept so
    /// `pass_rng` stays seed-keyed).
    #[allow(dead_code)] // read only by `pass_rng` until Phase 3
    seed: u64,
    /// The main stream — the biome, blob, ore, liquid, dungeon, tree and
    /// tail-till-the-end draws (`mod.rs`'s `rng`).
    pub(crate) rng: Rng,
    /// The detail stream — the ocean caves, fragile ice, underground jungle
    /// trees, exposed gems and vines (`drng`). (The floating islands moved
    /// onto their own `pass_rng("Floating Islands")` slot — W4-g44.)
    pub(crate) drng: Rng,
    /// The structures stream — shrines, chests, altars, pyramids, pots,
    /// hives, forts, temple, mini-biomes (`srng`).
    pub(crate) srng: Rng,
    /// The chest-stocking hook (S1-A-4) — `None` on the plain `generate`
    /// path (the tr-core tests), `Some` when the app stocks the world's
    /// chests at generation time (`generate_with_chest_stock`). Each chest
    /// placement site hands its event to it — the C#'s `AddBuriedChest`
    /// inline roll.
    pub(crate) chest_stock: Option<&'a mut super::chest_stock::ChestStockHook<'a>>,
    /// The worldgen progress/controller hook (S1-E-17) — `None` on the plain
    /// `generate` path (the tr-core tests and every pre-S1-E-17 caller),
    /// `Some` when the app drives the generation through the loading screen
    /// (`generate_with_progress`). The hook is the `WorldGenerator` pass-loop
    /// seam: `run` calls `begin_step`/`end_step` around each step exactly
    /// where `WorldGenerator.RunPass` calls `progress.Start(weight)` /
    /// `progress.End()` (`WorldGenerator.cs:498`/`:507`). No RNG draw rides
    /// the hook — the stream contract is untouched.
    pub(crate) progress: Option<&'a mut dyn GenProgressHook>,
}

/// The owned RNG state of the pipeline — the world seed plus the three
/// contract streams. No borrows, so the resumable [`GenerationRunner`] holds
/// it across frames; [`Streams::from_core`] wraps it with the per-call
/// borrowed hooks. The field layout mirrors [`Streams`]'s RNG half exactly.
#[derive(Clone)]
pub(crate) struct StreamCore {
    seed: u64,
    pub(crate) rng: Rng,
    pub(crate) drng: Rng,
    pub(crate) srng: Rng,
}

impl StreamCore {
    pub(crate) fn new(seed: u64) -> StreamCore {
        StreamCore {
            seed,
            rng: Rng(seed ^ 0xA076_1D64_78BD_642F),
            drng: Rng(seed ^ 0x5DEE_CE66_D1A4_9B5F),
            srng: Rng(seed ^ 0x9E37_79B9_7F4A_7C15),
        }
    }

    /// The per-pass stream — the port's model of the vanilla per-pass
    /// re-seed (`WorldGenerator.cs:497`). See [`Streams::pass_rng`].
    #[allow(dead_code)]
    pub(crate) fn pass_rng(&self, name: &str) -> Rng {
        Rng(self.seed ^ fnv1a64(name))
    }
}

/// The pass-loop progress seam (`WorldGenerator.GenerateWorld`/`RunPass`,
/// `WorldGenerator.cs:419-515`): the driver the loading screen's
/// `GenerationProgress` + `Controller` implement. `run` calls the pair around
/// every executed step; `should_abort` is the `QueuedAbort` check the C#
/// loop runs at the top of each iteration (`:433-437`).
pub trait GenProgressHook {
    /// `GenerateWorld`'s `this._progress.TotalWeight = ...Sum(p.Weight)`
    /// (`WorldGenerator.cs:424`) — called once before the first step with
    /// the sum of the executed steps' weights (the port's step model: each
    /// executed step banks its vanilla slot's weight once, so the total is
    /// exactly what `begin_step` will hand out — `TotalProgress` reaches
    /// 1.0 on completion).
    fn begin_generation(&mut self, total_weight: f64);
    /// `RunPass`'s `this._progress.Start(pass.Weight)` (`WorldGenerator.cs:498`)
    /// — `name` is the executed step's display name (`EXECUTED_PIPELINE`'s
    /// `name`; the message table `worldgen::progress::step_message` keys on
    /// it), `weight` its vanilla slot's `PassLegacy._weightMap` entry (1.0
    /// where the map has none).
    fn begin_step(&mut self, name: &str, weight: f64);
    /// `RunPass`'s `this._progress.End()` (`WorldGenerator.cs:507`).
    fn end_step(&mut self);
    /// `GenerateWorld`'s loop-top `if (this._controller.QueuedAbort)`
    /// (`WorldGenerator.cs:433-437`) — true stops the pipeline before the
    /// next step applies.
    fn should_abort(&self) -> bool;
}

impl<'a> Streams<'a> {
    pub(crate) fn new(seed: u64) -> Streams<'a> {
        let core = StreamCore::new(seed);
        Streams {
            seed: core.seed,
            rng: core.rng,
            drng: core.drng,
            srng: core.srng,
            chest_stock: None,
            progress: None,
        }
    }

    /// Wrap an owned RNG core with the per-call borrowed hooks — the
    /// resumable runner's `advance` builds one of these per step.
    pub(crate) fn from_core(
        core: StreamCore,
        chest_stock: Option<&'a mut super::chest_stock::ChestStockHook<'a>>,
        progress: Option<&'a mut dyn GenProgressHook>,
    ) -> Streams<'a> {
        Streams {
            seed: core.seed,
            rng: core.rng,
            drng: core.drng,
            srng: core.srng,
            chest_stock,
            progress,
        }
    }

    /// The owned RNG half — the resumable runner persists this across frames
    /// after each step (the borrowed hooks drop with the `Streams`).
    pub(crate) fn core(&self) -> StreamCore {
        StreamCore {
            seed: self.seed,
            rng: self.rng.clone(),
            drng: self.drng.clone(),
            srng: self.srng.clone(),
        }
    }

    /// The per-pass stream — the port's model of the vanilla per-pass
    /// re-seed (`WorldGenerator.cs:497`: `Main.rand = new UnifiedRandom(
    /// this._seed)` runs before every pass applies). Deviations from the
    /// vanilla fact, both deliberate and recorded in `docs/ANALYSIS.md` as
    /// the faithful passes land: xorshift stands in for the Knuth subtractive
    /// `UnifiedRandom`, and each pass draws from its own name-mixed stream
    /// (`seed ^ fnv1a64(name)`) instead of every pass re-drawing the same
    /// world-seed sequence — the isolation is what makes a chain insertion
    /// shift no other pass's draws. The three contract streams above are
    /// untouched by this.
    #[allow(dead_code)] // the per-pass stream contract — consumed from Phase 3 on
    pub(crate) fn pass_rng(&self, name: &str) -> Rng {
        Rng(self.seed ^ fnv1a64(name))
    }

    /// The per-pass stream as a [`crate::UnifiedRandom`] — the same name-mixed
    /// seed ([`Self::pass_rng`]) but the C#'s own Knuth subtractive algorithm,
    /// for the passes whose ported helpers already draw on `UnifiedRandom`
    /// (the gem-tree grower `growth::try_growing_tree_by_type`, W4-d106 R4's
    /// Stalac pass). The seed is the low 32 bits of the mixed state, wrapped
    /// to `i32` (the `UnifiedRandom(int)` ctor). Isolation is identical to
    /// `pass_rng`: a fresh stream per call, no other step's ledger shifts.
    pub(crate) fn pass_unified(&self, name: &str) -> crate::UnifiedRandom {
        crate::UnifiedRandom::new((self.seed ^ fnv1a64(name)) as u32 as i32)
    }
}

