fn step_terrain_height_map(
    _world: &mut World,
    gv: &mut GenVars,
    streams: &mut Streams,
    _opts: &GenOptions,
    noise: &Noise,
    _pass_config: &ConfigSection,
) {
    let (width, height) = (_world.width, _world.height);
    // `Reset`'s beach draws (`WorldGen.cs:11415-11440`), taken at the head of
    // the terrain step — the first consumer of the anchors (vanilla draws
    // them in Reset before every pass; the spans step stays the stand-in for
    // the later jungle draw). `Next(300, 340)` per side; the tenth-anniversary
    // fixed 340 is skipped (no seed framework, always the random branch); the
    // dungeon side is fixed Right (M5-BIOME) so the left side always adds
    // `beachSandDungeonExtraWidth` = 40 and the right side always takes the
    // `beachSandJungleExtraWidth` = 20 arm (`:11194-11195`,
    // `:11420-11427` / `:11433-11440`).
    let (left_beach_end, right_beach_start) = {
        let mut brng = streams.pass_rng("Beaches");
        let left = brng.range(300, 340) + 40;
        let right = width - (brng.range(300, 340) + 20);
        (left, right)
    };
    gv.left_beach_end = left_beach_end;
    gv.right_beach_start = right_beach_start;
    gv.map = Some(terrain::surface_height_map(
        width,
        height,
        noise,
        left_beach_end,
        right_beach_start,
    ));
}

/// `DunesAndPyramidLocations` (`WorldGen.cs:11517-11579`): the dune carver and
/// the pyramid-slot anchors. The `Count`/`ChanceOfPyramid` options come from
/// the pass's config section (`Configuration.json`'s `Passes.Dunes`); the snow
/// band's start is the terrain fill's eastern third (`terrain.rs:242`).
fn step_dunes(
    world: &mut World,
    gv: &mut GenVars,
    streams: &mut Streams,
    _opts: &GenOptions,
    _noise: &Noise,
    pass_config: &ConfigSection,
) {
    let count = pass_config
        .get_range("Count")
        .map_or(1, |r| r.get_random(&mut streams.pass_rng("Dunes"), world.width, world.height));
    let chance = pass_config
        .get_f64("ChanceOfPyramid")
        .unwrap_or(0.8);
    let anchors = desert_dunes::dunes(
        world,
        gv,
        world.width * 2 / 3,
        world.world_surface,
        count,
        chance,
        &mut streams.pass_rng("Dunes"),
    );
    // `GenVars.PyrX/PyrY/numPyr` (`GenVars.cs:156-160`): the anchors the
    // Pyramids step consumes (the append is the C#'s `:11570-11572`).
    for (x, y) in anchors {
        gv.pyr_x.push(x);
        gv.pyr_y.push(y);
        gv.num_pyr += 1;
    }
}

