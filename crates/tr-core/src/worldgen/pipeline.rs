/// `Main.tileFrameImportant` boot statics — the pre-pass setup the vanilla
/// `Reset` performs for frame-important kinds (`Main.cs:7663-7687`,
/// `:7415-7417`, `:7632`; the M1.4-TO-4 families). Vanilla worlds honour
/// them from boot, so a generated world must too: `framing` keeps the stored
/// frames of these kinds and the kill cascade reaches them.
pub(crate) fn boot_statics(world: &mut World) {
    world.frame_important = vec![false; td::TILE_COUNT];
    world.frame_important[tree::TREE as usize] = true;
    // The rest of the tree trunks (`Main.cs:7678/:7760-7775`): the ash trunk
    // 72 and the variant kinds 583-589 (the gem trees), 596/616 (the vanity
    // trees) and 634 (the ash tree). All of them are frame-important, so the
    // framer keeps their stored frames and the kill cascade reaches them
    // (`TileFrameImportant`'s tree arms, `WorldGen.cs:85876-85911`).
    world.frame_important[72] = true;
    for kind in 583..=589 {
        world.frame_important[kind] = true;
    }
    world.frame_important[596] = true;
    world.frame_important[616] = true;
    world.frame_important[634] = true;
    world.frame_important[3] = true;
    world.frame_important[4] = true;
    // The water plants (`Main.cs:7366-7378`): the lily pad 518, the cattail
    // 519, the seaweed 549 and the sea oats 529 are frame-important, so the
    // framer keeps the frame rows their growth arms write (`GrowCatTail`
    // `WorldGen.cs:58974-59082`, `GrowCheckSeaweed` `:58917`).
    for kind in [518u16, 519, 529, 549] {
        world.frame_important[kind as usize] = true;
    }
    // `Main.tileFrameImportant` boot statics for the M1.4-TO-4 families
    // (sunflower 27 / pots 28 `Main.cs:7663-7664`, clay pot 78 `:7682`,
    // herbs 82-84 `:7685-7687`, piles 185-187 `:7415-7417`, planter box 380
    // `:7632`) — vanilla worlds honour them from boot, so a generated world
    // must too: `framing` keeps the stored frames of these kinds and the kill
    // cascade reaches them.
    world.frame_important[27] = true;
    world.frame_important[28] = true;
    // The demon altar 26 and the shadow orb 31 (`Main.cs:7661/:7666`) — the
    // M5-BIOME phase-4 evil pass writes their style/frame data, which the
    // framer must keep.
    world.frame_important[26] = true;
    world.frame_important[31] = true;
    // The temple tiles the temple pass writes — the dart trap 137
    // (`Main.cs:7431`) and the Lihzahrd altar 237 (`Main.cs:10234`) are
    // frame-important, so the framer keeps their stored frames; the
    // Lihzahrd brick 226 is not (bricks auto-frame).
    world.frame_important[137] = true;
    world.frame_important[237] = true;
    world.frame_important[78] = true;
    world.frame_important[82] = true;
    world.frame_important[83] = true;
    world.frame_important[84] = true;
    world.frame_important[185] = true;
    world.frame_important[186] = true;
    world.frame_important[187] = true;
    world.frame_important[380] = true;
    // The ocean tiles the ocean passes write — the palm trunk 323, the
    // coral 81, the beach piles 324, the shell piles 495, the sea oats 529
    // (`Main.cs:7376`) and the oasis plants 530 (`:7385`) are all
    // style-driven, not auto-framed, so the framer keeps their stored frames.
    world.frame_important[323] = true;
    world.frame_important[81] = true;
    world.frame_important[324] = true;
    world.frame_important[495] = true;
    world.frame_important[529] = true;
    world.frame_important[530] = true;
    // Abigail's flower 624 (`Main.cs:7366-7378`'s frame-important list): the
    // M5-SPREAD-1e growth arm writes its 0/0 frame
    // (`WorldGen.TryGrowingAbigailsFlower`, `WorldGen.cs:73049-73073`), and the
    // framer must keep it instead of autotiling a 1x1 flower.
    world.frame_important[624] = true;
    world.frame_important[549] = true;
    // The chest family — the sapling 20, the chest 21, the golden-chest style
    // 467 and the two container kinds 441/468 (`Main.cs:7655-7659`; the
    // vanilla bit is a no-op in `WorldGen.TileFrameImportant` for them, so a
    // chest keeps its stored frames). Vanilla worlds honour them from boot,
    // so a generated world must too: without the bit the load-time
    // `frame_world` re-frames every chest tile through its object def, the
    // 2x2 anchor frames (`frameX == 0 && frameY == 0` — the
    // `generate_world_chests` and `is_locked` scans) are lost, and the
    // chest-anchor scans miss every chest in a loaded world.
    world.frame_important[20] = true;
    world.frame_important[21] = true;
    world.frame_important[467] = true;
    world.frame_important[441] = true;
    world.frame_important[468] = true;
}

/// The vanilla `RunPass` shape over the ported steps: per step, build the
/// pass's config view (`WorldGenerator.cs:501`) and apply. The config read
/// draws no RNG; today's adapters ignore the view (the shape-level passes
/// keep their own pinned constants).
pub(crate) fn run(
    world: &mut World,
    streams: &mut Streams,
    opts: &GenOptions,
    noise: &Noise,
    config: &WorldGenConfig,
) {
    let mut gv = GenVars::default();
    // The `WorldGen.Reset()` seed-flag tail (`WorldGen.cs:11125-11127`,
    // `:11216-11223`): the derived combo booleans plus the `crimsonLeft`
    // half-roll. Vanilla draws it from the pre-pass `genRand`; the port
    // gives it its own `pass_rng("Reset")` stream so every existing
    // per-pass draw schedule is byte-identical for a classic world.
    let mut reset_rng = streams.pass_rng("Reset");
    gv.crimson_left = reset_rng.range(0, 2) == 1;
    gv.flip_infections = opts.flags.flip_infections();
    for step in EXECUTED_PIPELINE {
        // The vanilla `RunPass` trace (`WorldGenerator.cs`: `Trace.WriteLine`
        // per `GenPassResult`) — the executed-step log names the step, its
        // vanilla slot and that slot's progress weight.
        let row = VANILLA_CHAIN.iter().find(|p| p.name == step.vanilla);
        log::debug!(
            "worldgen pass '{}' (vanilla '{}', weight {:.4})",
            step.name,
            step.vanilla,
            row.map_or(1.0, |p| p.weight)
        );
        let pass_config = config.pass(step.name);
        (step.f)(world, &mut gv, streams, opts, noise, &pass_config);
    }
}

