//! The worldgen pass scaffold — the vanilla-shaped pipeline over the ported
//! passes.
//!
//! Vanilla runs worldgen as a code-declared chain of named passes
//! (`WorldGen.AddPasses`, `WorldGen.cs:11502-22143`, 106 passes for a classic
//! world) executed by a `WorldGenerator` loop that hands every pass its own
//! `UnifiedRandom(worldSeed)` (`WorldGenerator.cs:497`) and the pass's JSON
//! options (`WorldGenConfiguration.GetPassConfiguration`). This module
//! declares that shape in two tables:
//!
//! - [`VANILLA_CHAIN`] — the full vanilla chain as data: name (the
//!   `GenPassNameID` string), progress weight (`PassLegacy._weightMap`),
//!   the `AddGenerationPass` anchor and the conditional-registration gate.
//!   It is the model and the slot registry future passes register into —
//!   it is never walked at runtime.
//! - [`EXECUTED_PIPELINE`] — the port's pipeline: today's 41 steps in
//!   today's exact call order, each an adapter that calls the existing
//!   `pub(crate)` pass fn unchanged. The order is NOT the vanilla order (the
//!   deviations are pinned by the world contract — see the per-step
//!   comments and `docs/ANALYSIS.md`); reordering would shift the shared
//!   xorshift streams and change every generated byte.
//!
//! The runner mirrors vanilla `RunPass`: per step it builds the pass's
//! config view (`config.pass(name)`) and hands it to the adapter; today's
//! adapters ignore it (the port's shape-level passes keep their own pinned
//! constants), but future passes read their options from there instead of
//! hardcoding. A future pass slots between existing steps only with its own
//! RNG stream ([`Streams::pass_rng`] — `Rng(seed ^ fnv1a64(name))`; vanilla's
//! per-pass re-seed is what makes its chain insertion-safe); the three
//! contract streams here must never shift.

